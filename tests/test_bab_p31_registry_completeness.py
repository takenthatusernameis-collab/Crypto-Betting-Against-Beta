"""Acceptance tests for P31 WP1: registry completeness guard.

Contract (from HANDOFF.md P31 WP1):

* A test enumerates every ``*.json`` under ``research_state/bab_p2*/`` and
  fails if any committed research artifact is not covered by the replay
  registry (``scripts/bab_replay_full.py` REGISTRY) or explicitly
  allow-listed with a written reason.
* This makes the 8/28 -> 27/28 coverage gap structurally impossible to
  re-create: a newly added research artifact that escapes the registry fails
  this test.
* The P27 decision sidecar (``p27_decision_sidecar.json``) is the single
  committed JSON artifact intentionally outside the full-artifact registry:
  it is byte-replayed by ``scripts/bab_replay_decisions.py`` (P29 WP2), so it
  is allow-listed with a written reason.
"""

from __future__ import annotations

import importlib.util
import json
import os
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
REPLAY = REPO_ROOT / "scripts" / "bab_replay_full.py"
RESEARCH = REPO_ROOT / "research_state"

# Committed JSON artifacts intentionally outside the full-artifact replay
# registry, each with a written reason. The P27 decision sidecar is byte
# replayed by scripts/bab_replay_decisions.py (P29 WP2). The P29 provenance
# audit is a generated ledger written by scripts/bab_replay_full.py --xproc
# (P29 WP1); it has no build_*() entry point and is regenerated byte-identically
# each run, so it is not a source research artifact.
ALLOW_LIST: dict[str, str] = {
    "research_state/bab_p27/p27_decision_sidecar.json": (
        "covered by scripts/bab_replay_decisions.py (P29 WP2 decision-doc "
        "replay), not the full-artifact replay registry"
    ),
    "research_state/bab_p29/provenance_audit.json": (
        "generated ledger written by scripts/bab_replay_full.py --xproc "
        "(P29 WP1); no build_*() entry point; regenerated byte-identically "
        "each run"
    ),
}


def _load_registry():
    spec = importlib.util.spec_from_file_location("bab_replay_full", REPLAY)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod.REGISTRY


def _committed_json_paths() -> list[str]:
    paths: list[str] = []
    for sub in sorted(RESEARCH.iterdir()):
        if not sub.is_dir() or not sub.name.startswith("bab_p2"):
            continue
        for path in sorted(sub.iterdir()):
            if path.is_file() and path.suffix == ".json":
                paths.append(str(path.relative_to(REPO_ROOT)))
    return paths


def test_script_exists():
    assert REPLAY.is_file(), f"missing {REPLAY}"


def test_registry_completeness_covers_every_committed_json():
    registry = _load_registry()
    covered = {
        f"research_state/{entry['dir']}/{entry['name']}.json" for entry in registry
    }
    committed = _committed_json_paths()
    missing = [
        p for p in committed if p not in covered and p not in ALLOW_LIST
    ]
    assert not missing, (
        "committed research artifacts not covered by the replay registry and "
        f"not allow-listed: {missing}. Add them to the REGISTRY in "
        "scripts/bab_replay_full.py or allow-list them with a written reason."
    )


def test_allow_list_is_precise():
    registry = _load_registry()
    covered = {
        f"research_state/{entry['dir']}/{entry['name']}.json" for entry in registry
    }
    committed = set(_committed_json_paths())
    for path, reason in ALLOW_LIST.items():
        assert path in committed, f"allow-listed path does not exist: {path}"
        assert path not in covered, (
            f"allow-listed path {path} is already covered by the registry; "
            "remove it from the allow list"
        )
        assert reason, f"allow-listed path {path} has no written reason"


def test_no_ruff_errors_on_new_files():
    ruff = subprocess.run(
        [sys.executable, "-m", "ruff", "check", str(__file__)],
        cwd=REPO_ROOT,
        capture_output=True,
        text=True,
    )
    assert ruff.returncode == 0, f"ruff must pass: {ruff.stdout} {ruff.stderr}"
